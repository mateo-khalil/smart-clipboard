import Foundation

public enum KnownTypes {
    public static let text = "public.utf8-plain-text"
    public static let rtf = "public.rtf"
    public static let html = "public.html"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let tiff = "public.tiff"

    /// Marks this app's own writes, so a paste is not recorded as a new copy.
    public static let ownMarker = "com.mateoduran.smartclipboard.own"
    public static let source = "org.nspasteboard.source"

    /// Best first: already-compressed formats cost far less disk than TIFF.
    public static let imagePriority = [png, jpeg, heic, tiff]

    /// Password managers and similar tools flag their copies with these.
    public static let alwaysIgnored: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.agilebits.onepassword",
        "net.antelle.keeweb",
    ]
}

public struct IgnoreRules: Sendable, Equatable, Codable {
    public var apps: Set<String>
    /// Inverts `apps`: only the listed apps are recorded.
    public var onlyListedApps: Bool
    public var types: Set<String>
    public var patterns: [String]

    public init(apps: Set<String> = [], onlyListedApps: Bool = false, types: Set<String> = [], patterns: [String] = []) {
        self.apps = apps
        self.onlyListedApps = onlyListedApps
        self.types = types
        self.patterns = patterns
    }

    public func ignores(types present: [String]) -> Bool {
        present.contains { KnownTypes.alwaysIgnored.contains($0) || types.contains($0) }
    }

    public func ignores(app: String?) -> Bool {
        if onlyListedApps {
            guard let app else { return true }
            return !apps.contains(app)
        }
        guard let app else { return false }
        return apps.contains(app)
    }

    /// A broken pattern is skipped instead of blocking every copy.
    public func ignores(text: String) -> Bool {
        guard !patterns.isEmpty, !text.isEmpty else { return false }
        let range = NSRange(text.startIndex..., in: text)
        return patterns.contains { pattern in
            guard let regex = try? NSRegularExpression(pattern: pattern) else { return false }
            return regex.firstMatch(in: text, range: range) != nil
        }
    }
}
